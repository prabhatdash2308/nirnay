-- ============================================================
-- 1. Helper function: automatically maintain updated_at
-- ============================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


-- ============================================================
-- 2. User profiles
-- ============================================================

create table if not exists public.user_profiles (
  id bigint generated by default as identity primary key,

  user_id text not null unique,

  full_name text,
  email text,
  phone text,
  avatar_url text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- ============================================================
-- 3. Financial profiles
-- ============================================================

create table if not exists public.financial_profiles (
  id bigint generated by default as identity primary key,

  user_id text not null unique
    references public.user_profiles(user_id)
    on delete cascade,

  monthly_income numeric(14,2),
  monthly_expenses numeric(14,2),
  monthly_investment_budget numeric(14,2),
  annual_insurance_budget numeric(14,2),

  risk_profile text
    check (
      risk_profile is null
      or risk_profile in (
        'conservative',
        'moderate',
        'aggressive'
      )
    ),

  financial_experience text
    check (
      financial_experience is null
      or financial_experience in (
        'beginner',
        'intermediate',
        'advanced'
      )
    ),

  primary_goals text[] not null default '{}',

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint financial_profile_income_non_negative
    check (
      monthly_income is null
      or monthly_income >= 0
    ),

  constraint financial_profile_expenses_non_negative
    check (
      monthly_expenses is null
      or monthly_expenses >= 0
    ),

  constraint financial_profile_investment_budget_non_negative
    check (
      monthly_investment_budget is null
      or monthly_investment_budget >= 0
    ),

  constraint financial_profile_insurance_budget_non_negative
    check (
      annual_insurance_budget is null
      or annual_insurance_budget >= 0
    )
);


-- ============================================================
-- 4. Insurance policies
-- ============================================================

create table if not exists public.insurance_policies (
  id bigint generated by default as identity primary key,

  user_id text not null
    references public.user_profiles(user_id)
    on delete cascade,

  policy_type text not null
    check (
      policy_type in (
        'health',
        'motor',
        'life',
        'other'
      )
    ),

  provider text not null,
  policy_name text not null,

  policy_number text,

  premium_amount numeric(14,2),
  premium_frequency text
    check (
      premium_frequency is null
      or premium_frequency in (
        'monthly',
        'quarterly',
        'half_yearly',
        'yearly',
        'one_time'
      )
    ),

  sum_insured numeric(16,2),

  start_date date,
  renewal_date date,

  status text not null default 'active'
    check (
      status in (
        'active',
        'expired',
        'cancelled',
        'pending'
      )
    ),

  metadata jsonb not null default '{}',

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint insurance_premium_non_negative
    check (
      premium_amount is null
      or premium_amount >= 0
    ),

  constraint insurance_sum_insured_non_negative
    check (
      sum_insured is null
      or sum_insured >= 0
    )
);


