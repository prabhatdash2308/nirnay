      severity in (
        'info',
        'warning',
        'important',
        'critical'
      )
    ),

  scheduled_for timestamptz,
  read_at timestamptz,

  metadata jsonb not null default '{}',

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


